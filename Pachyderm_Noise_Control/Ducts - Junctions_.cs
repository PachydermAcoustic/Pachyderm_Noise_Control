            //For other branch, subscripts 1 and 2 change places.        
            public static void Junction(State S, JunctionType type, double[] Vertical_inches_takeoff, double[] horizontal_inches_takeoff, Hare.Geometry.Vector[] dir, out State[] Outlets, List<double> Bend_Radius, out double[] attenuation, out double[][] Regen_b, double[] volumes = null)
            {
                if (volumes == null || volumes.Length < horizontal_inches_takeoff.Length) volumes = new double[horizontal_inches_takeoff.Length];

                attenuation = new double[volumes.Length];
                double[] sections = new double[volumes.Length];
                double[] Velocity_s = new double[volumes.Length];
                Regen_b = new double[volumes.Length][];
                double supply_velocity_s = S.Velocity / 60;

                int Continuation_id = 0;
                double greatestarea = Vertical_inches_takeoff[0] * horizontal_inches_takeoff[0];
                double[] diameters_ft = new double[Vertical_inches_takeoff.Length];
                double total_area = 0;
                for (int i = 0; i < Vertical_inches_takeoff.Length; i++) total_area += horizontal_inches_takeoff[i] * Vertical_inches_takeoff[i];

                for (int i = 0; i < Vertical_inches_takeoff.Length; i++)
                {
                    double area = Vertical_inches_takeoff[i] == 0 ? Math.PI * Math.Pow(horizontal_inches_takeoff[i] / 2, 2) : Vertical_inches_takeoff[i] * horizontal_inches_takeoff[i];
                    diameters_ft[i] = Math.Sqrt(4 * (area / 144) / Math.PI);
                    if (volumes[i] == 0) volumes[i] = S.Volume * area / total_area;
                    if (area > greatestarea) Continuation_id = i;
                }

                for (int i = 0; i < volumes.Length; i++)
                {
                    attenuation[i] = 10 * Math.Log10(volumes[i] / S.Volume);
                    sections[i] = Math.PI * diameters_ft[i] * diameters_ft[i] / 4;
                    Velocity_s[i] = volumes[i] / (sections[i] * 60); //S.Volume / (section_Take[i] / 144 * 60);
                    if (i == Continuation_id) continue;
                    Regen_b[i] = new double[8];
                    for (int oct = 0; oct < 8; oct++)
                    {
                        double f = 62.5 * Math.Pow(2, oct);
                        double Strouhal = f * diameters_ft[i] / Velocity_s[i];
                        double Radius_Correction = (1 - (Bend_Radius[i] / (12 * diameters_ft[i])) / 0.15) * (6.793 - 1.86 * Math.Log10(Strouhal));
                        double m = supply_velocity_s / Velocity_s[i];
                        double Turbulence_Correction = -1.667 + 1.8 * m - 0.133 * m * m;
                        double Char_Spectrum_Kj = -21.6 + 12.388 * Math.Pow(m, 0.673) - 16.482 * Math.Pow(m, -0.303) * Math.Log10(Strouhal) - 5.047 * Math.Pow(m, -0.254) * Math.Pow(Math.Log10(Strouhal), 2);
                        Regen_b[i][oct] = Char_Spectrum_Kj + 10 * Math.Log10(f / 63) + 50 * Math.Log10(Velocity_s[i]) + 10 * Math.Log10(sections[i]) + 10 * Math.Log10(diameters_ft[i]) + Radius_Correction + Turbulence_Correction;
                    }
                }

                Regen_b[Continuation_id] = new double[8];
                double logDmDb = 0;
                switch (type)
                {
                    case JunctionType.Takeoff_90:
                        for (int oct = 0; oct < 8; oct++) Regen_b[Continuation_id][oct] = 0;
                        for (int i = 0; i < diameters_ft.Length; i++)
                        {
                            if (i == Continuation_id) continue;
                            logDmDb = 20 * Math.Log10((diameters_ft[Continuation_id]) / diameters_ft[i]);
                            for (int o = 0; o < 8; o++) Regen_b[Continuation_id][o] += logDmDb;
                        }
                        break;
                    case JunctionType.T_Junction:
                        if (sections[0] == sections[1])
                        {
                            for (int o = 0; o < 8; o++)
                            {
                                for (int i = 0; i < diameters_ft.Length; i++) Regen_b[i][o] += 3;
                            }
                            break;
                        }
                        for (int oct = 0; oct < 8; oct++) Regen_b[Continuation_id][oct] = 0;
                        for (int i = 0; i < diameters_ft.Length; i++)
                        {
                            if (i == Continuation_id) continue;
                            for (int o = 0; o < 8; o++) Regen_b[Continuation_id][o] = 10 * Math.Log10(Math.Pow(10f, Regen_b[Continuation_id][o] / 10) + Math.Pow(10f, (Regen_b[i][o]) / 10));
                        }
                        break;
                    case JunctionType.X_Junction:
                        for (int oct = 0; oct < 8; oct++) Regen_b[Continuation_id][oct] = 0;

                        for (int i = 0; i < diameters_ft.Length; i++)
                        {
                            if (i == Continuation_id) continue;
                            logDmDb = 20 * Math.Log10((diameters_ft[Continuation_id]) / diameters_ft[i]);
                            for (int o = 0; o < 8; o++) Regen_b[Continuation_id][o] = 10 * Math.Log10(Math.Pow(10f, Regen_b[Continuation_id][o] / 10) + Math.Pow(10f, (Regen_b[i][o] + logDmDb) / 10));
                        }
                        break;
                }

                Outlets = new State[volumes.Length];
                for (int i = 0; i < volumes.Length; i++)
                {
                    Outlets[i] = (S.Clone() as State) - new double[8] { -attenuation[i], -attenuation[i], -attenuation[i], -attenuation[i], -attenuation[i], -attenuation[i], -attenuation[i], -attenuation[i] };
                    Outlets[i].Volume = volumes[i];
                    Outlets[i].Velocity = Velocity_s[i];
                    dir[i].Normalize();
                    Outlets[i].Direction = dir[i];
                    Outlets[i].dimensions = new double[2] { horizontal_inches_takeoff[i], Vertical_inches_takeoff[i] };
                }

                double[][] ATT = new double[attenuation.Length][];
                for (int i = 0; i < attenuation.Length; i++) ATT[i] = new double[8] { -attenuation[i], -attenuation[i], -attenuation[i], -attenuation[i], -attenuation[i], -attenuation[i], -attenuation[i], -attenuation[i] };

                for (int j = 0; j < diameters_ft.Length; j++)
                {
                    if (Math.Abs(dir[j].dx + dir[j].dy) > 0.01)
                    {
                        if (Hare.Geometry.Hare_math.Dot(S.Direction, dir[j]) > 0.95)
                        {
                            List<Hare.Geometry.Point> Pts = new List<Hare.Geometry.Point>();
                            int ct = (int)Math.Ceiling(((Bend_Radius[j] + S.dimensions[0]) / 12) / Duct_Model.Instance.delta_D);
                            for (int i = 0; i < ct; i++)
                            {
                                Pts.Add(S.Location + dir[j] * i);
                            }
                            Duct_Model.Instance.AddComponent(S.ModelNode, ATT[j], Regen_b[j], Duct_Model.NoiseType.Aerodynamic, Pts.ToArray(), horizontal_inches_takeoff[j], Vertical_inches_takeoff[j], ref Outlets[j]);
                        }
                        if (Bend_Radius[j] > 0)
                        {
                            List<Hare.Geometry.Point> Pts = new List<Hare.Geometry.Point>();
                            double val = Duct_Model.Instance.delta_D / (2 * Math.PI * Bend_Radius[j] * 0.0254);
                            double dtheta = 2 * Math.PI * val;//Math.Acos((val > 1 ? 1 : val));
                            Hare.Geometry.Vector Perp = Hare.Geometry.Hare_math.Cross(S.Direction, new Hare.Geometry.Vector(0, 0, 1));
                            if (Hare.Geometry.Hare_math.Dot(dir[j], Perp) > 0)
                            {
                                Perp *= -1;
                            }
                            double radiusCtr = Bend_Radius[j] + horizontal_inches_takeoff[j] / 2;
                            Hare.Geometry.Point center = S.Location - Perp * (radiusCtr) * 0.0254;
                            double stheta = Math.Atan2(S.Direction.dy, S.Direction.dx);
                            double etheta = Math.Atan2(Outlets[j].Direction.dy, Outlets[j].Direction.dx);
                            double diff = (etheta - stheta);
                            if (diff > Math.PI) diff -= Math.PI;
                            else if (diff < -Math.PI) diff += Math.PI;
                            int diffdir = diff > 0 ? 1 : -1;
                            int cttheta = (int)(diffdir * Math.Ceiling(1 + Math.Abs(diff) / dtheta));
                            double dz = dir[j].dz * Duct_Model.Instance.delta_D;
                            for (int i = 0; i != cttheta; i += diffdir)
                            {
                                Hare.Geometry.Vector v = new Hare.Geometry.Vector(Math.Cos(i * dtheta + stheta), Math.Sin(i * dtheta + stheta), dz * i);
                                v.Normalize();
                                Pts.Add(center + (radiusCtr * 0.0254) * v);
                            }
                            Duct_Model.Instance.AddComponent(S.ModelNode, ATT[j], Regen_b[j], Duct_Model.NoiseType.Aerodynamic, Pts.ToArray(), horizontal_inches_takeoff[j], Vertical_inches_takeoff[j], ref Outlets[j]);
                        }
                        else
                        {
                            List<Hare.Geometry.Point> Pts = new List<Hare.Geometry.Point>();
                            double D1 = (horizontal_inches_takeoff[j] / 12) * .3048 / 2;
                            double D2 = (horizontal_inches_takeoff[j] / 12) * .3048 / 2;
                            int D1ct = (int)Math.Ceiling(D1 / Duct_Model.Instance.delta_D);
                            int D2ct = (int)Math.Ceiling(D2 / Duct_Model.Instance.delta_D);
                            double dD1 = D1 / D1ct;
                            double dD2 = D2 / D2ct;
                            for (int i = 1; i < D1ct + 1; i++) Pts.Add(S.Location + dD1 * S.Direction * i);
                            Hare.Geometry.Vector Perp = Hare.Geometry.Hare_math.Cross(S.Direction, new Hare.Geometry.Vector(0, 0, 1));
                            Perp *= Hare.Geometry.Hare_math.Dot(dir[j], Perp) > 0 ? 1 : -1;
                            Hare.Geometry.Point pt = Pts[Pts.Count - 1];
                            for (int i = 1; i < D2ct + 1; i++) Pts.Add(pt + dD2 * dir[j] * i);
                            Duct_Model.Instance.AddComponent(S.ModelNode, ATT[j], Regen_b[j], Duct_Model.NoiseType.Aerodynamic, Pts.ToArray(), horizontal_inches_takeoff[j], Vertical_inches_takeoff[j], ref Outlets[j]);
                        }
                    }
                    else
                    {
                        if (Hare.Geometry.Hare_math.Dot(S.Direction, dir[j]) > 0.95)
                        {
                            List<Hare.Geometry.Point> Pts = new List<Hare.Geometry.Point>();
                            int ct = (int)Math.Ceiling(((Bend_Radius[j] + S.dimensions[1]) / 12) / Duct_Model.Instance.delta_D);
                            for (int i = 0; i < ct; i++)
                            {
                                Pts.Add(S.Location + dir[j] * i);
                            }
                            Duct_Model.Instance.AddComponent(S.ModelNode, ATT[j], Regen_b[j], Duct_Model.NoiseType.Aerodynamic, Pts.ToArray(), horizontal_inches_takeoff[j], Vertical_inches_takeoff[j], ref Outlets[j]);
                        }
                        if (Bend_Radius[j] > 0)
                        {
                            List<Hare.Geometry.Point> Pts = new List<Hare.Geometry.Point>();
                            //2 * Elbow_Radius * Math.Sin(Math.Acos(Hare.Geometry.Hare_math.Dot(S.Direction, R.Direction))/2);
                            double dtheta = 2 * Math.Asin(Duct_Model.Instance.delta_D / (2 * Bend_Radius[j]));
                            Hare.Geometry.Vector Lateral = S.Direction + Outlets[j].Direction / 2;
                            Hare.Geometry.Vector Axis = Hare.Geometry.Hare_math.Cross(S.Direction, dir[j]);
                            //Hare.Geometry.Vector Perp = Hare.Geometry.Hare_math.Cross(S.Direction, Axis);
                            Axis *= Hare.Geometry.Hare_math.Dot(dir[j], Axis) > 0 ? 1 : -1;
                            double radiusCtr = Bend_Radius[j] + Vertical_inches_takeoff[j] / 2;
                            Hare.Geometry.Point center = S.Location - Axis * (radiusCtr) * 0.0254;

                            Hare.Geometry.Vector diffx;
                            Hare.Geometry.Vector diffy;
                            //Check that the ray and the normal are both on the same side...
                            diffx = new Hare.Geometry.Vector(0, 0, 1);
                            diffy = Hare.Geometry.Hare_math.Cross(Axis, diffx);
                            diffx = Hare.Geometry.Hare_math.Cross(diffy, Axis);
                            diffx.Normalize();
                            diffy.Normalize();
                            Axis.Normalize();

                            double stheta = Math.Atan2(-Axis.dy, -Axis.dx);
                            double flatlengthS = Math.Sqrt(S.Direction.dx * S.Direction.dx + S.Direction.dy * S.Direction.dy);
                            double flatlengthR = Math.Sqrt(Outlets[j].Direction.dx * Outlets[j].Direction.dx + Outlets[j].Direction.dy * Outlets[j].Direction.dy);
                            double etheta = Math.Acos(flatlengthR * flatlengthS + S.Direction.dz * Outlets[j].Direction.dz);
                            int cttheta = (int)Math.Ceiling(etheta / dtheta);
                            dtheta = etheta / cttheta;
                            double dflat = dir[j].dz * Duct_Model.Instance.delta_D;
                            for (int i = 1; i < cttheta + 1; i++)
                            {
                                double x, y;
                                Hare.Geometry.Vector vect;
                                double theta = i * dtheta + stheta;
                                x = Math.Cos(theta) * Math.Sin(theta);
                                y = Math.Sin(theta) * Math.Sin(theta);
                                vect = (diffx * x) + (diffy * y);
                                vect.Normalize();
                                Pts.Add(center + radiusCtr * vect);
                            }
                            Duct_Model.Instance.AddComponent(S.ModelNode, ATT[j], Regen_b[j], Duct_Model.NoiseType.Aerodynamic, Pts.ToArray(), horizontal_inches_takeoff[j], Vertical_inches_takeoff[j], ref Outlets[j]);
                        }
                        else
                        {
                            List<Hare.Geometry.Point> Pts = new List<Hare.Geometry.Point>();
                            double D1 = (Vertical_inches_takeoff[j] / 12) * .3048 / 2;
                            double D2 = (Vertical_inches_takeoff[j] / 12) * .3048 / 2;
                            int D1ct = (int)Math.Ceiling(D1 / Duct_Model.Instance.delta_D);
                            int D2ct = (int)Math.Ceiling(D2 / Duct_Model.Instance.delta_D);
                            double dD1 = D1 / D1ct;
                            double dD2 = D2 / D2ct;
                            for (int i = 1; i < D1ct + 1; i++) Pts.Add(S.Location + dD1 * S.Direction * i);
                            Hare.Geometry.Vector Perp = Hare.Geometry.Hare_math.Cross(S.Direction, new Hare.Geometry.Vector(0, 0, 1));
                            Perp *= Hare.Geometry.Hare_math.Dot(dir[j], Perp) > 0 ? 1 : -1;
                            Hare.Geometry.Point pt = Pts[Pts.Count - 1];
                            for (int i = 1; i < D2ct + 1; i++) Pts.Add(pt + dD2 * dir[j] * i);
                            Duct_Model.Instance.AddComponent(S.ModelNode, ATT[j], Regen_b[j], Duct_Model.NoiseType.Aerodynamic, Pts.ToArray(), horizontal_inches_takeoff[j], Vertical_inches_takeoff[j], ref Outlets[j]);
                        }
                    }
